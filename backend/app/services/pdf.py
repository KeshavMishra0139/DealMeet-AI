"""PDF invoices and media kits (ReportLab). DejaVu Sans is bundled for the
rupee sign; it ships with its license in app/assets/fonts."""
from __future__ import annotations

import io
from pathlib import Path

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.units import mm
from reportlab.pdfbase import pdfmetrics
from reportlab.pdfbase.ttfonts import TTFont
from reportlab.pdfgen.canvas import Canvas

FONTS = Path(__file__).resolve().parents[1] / "assets" / "fonts"
VIOLET = colors.HexColor("#6D28D9")
MAGENTA = colors.HexColor("#BE185D")
ORANGE = colors.HexColor("#C2410C")
INK = colors.HexColor("#16132B")
MUTED = colors.HexColor("#5F5980")
LINE = colors.HexColor("#E7E4F0")
SOFT = colors.HexColor("#F3F1FA")

_registered = False


def _fonts() -> tuple[str, str]:
    global _registered
    try:
        if not _registered:
            pdfmetrics.registerFont(TTFont("JD", str(FONTS / "DejaVuSans.ttf")))
            pdfmetrics.registerFont(TTFont("JD-Bold", str(FONTS / "DejaVuSans-Bold.ttf")))
            _registered = True
        return "JD", "JD-Bold"
    except Exception:
        return "Helvetica", "Helvetica-Bold"


def money(v: float) -> str:
    regular, _ = _fonts()
    n = int(round(v))
    s = str(n)
    if len(s) > 3:
        head, tail = s[:-3], s[-3:]
        parts = []
        while len(head) > 2:
            parts.insert(0, head[-2:])
            head = head[:-2]
        if head:
            parts.insert(0, head)
        s = ",".join(parts + [tail])
    return f"{'₹' if regular == 'JD' else 'Rs. '}{s}"


def _brand_bar(c: Canvas, w: float, h: float) -> None:
    # Signature gradient as three bands across the top.
    band = w / 3
    for i, col in enumerate((VIOLET, MAGENTA, ORANGE)):
        c.setFillColor(col)
        c.rect(i * band, h - 4 * mm, band + 1, 4 * mm, stroke=0, fill=1)


def _wordmark(c: Canvas, x: float, y: float) -> None:
    regular, bold = _fonts()
    c.setStrokeColor(VIOLET)
    c.setLineWidth(1.6)
    c.circle(x + 3 * mm, y + 1.6 * mm, 2.6 * mm)
    c.setStrokeColor(MAGENTA)
    c.circle(x + 5.6 * mm, y + 1.6 * mm, 2.6 * mm)
    c.setFillColor(INK)
    c.setFont(bold, 13)
    c.drawString(x + 10 * mm, y, "JodiDar")
    c.setFillColor(MAGENTA)
    c.drawString(x + 10 * mm + c.stringWidth("JodiDar ", bold, 13), y, "AI")


def invoice_pdf(inv: dict, creator: dict, deal: dict | None) -> bytes:
    regular, bold = _fonts()
    buf = io.BytesIO()
    c = Canvas(buf, pagesize=A4)
    w, h = A4
    _brand_bar(c, w, h)
    _wordmark(c, 18 * mm, h - 22 * mm)
    c.setFont(bold, 22)
    c.setFillColor(INK)
    c.drawRightString(w - 18 * mm, h - 22 * mm, "Invoice")
    c.setFont(regular, 9.5)
    c.setFillColor(MUTED)
    c.drawRightString(w - 18 * mm, h - 28 * mm, f"{inv['number']}  ·  Issued {inv['issued']}")

    y = h - 48 * mm
    c.setFont(bold, 9)
    c.drawString(18 * mm, y, "FROM")
    c.drawString(105 * mm, y, "BILL TO")
    c.setFont(regular, 11)
    c.setFillColor(INK)
    c.drawString(18 * mm, y - 6 * mm, creator.get("name", "Creator"))
    c.drawString(105 * mm, y - 6 * mm, inv["to"])
    c.setFont(regular, 9.5)
    c.setFillColor(MUTED)
    c.drawString(18 * mm, y - 11 * mm, f"@{creator.get('handle', '')}")
    if creator.get("is_reference"):
        c.drawString(18 * mm, y - 16 * mm, "Reference profile (identity withheld)")

    y -= 34 * mm
    c.setFillColor(SOFT)
    c.rect(18 * mm, y - 2 * mm, w - 36 * mm, 9 * mm, stroke=0, fill=1)
    c.setFillColor(MUTED)
    c.setFont(bold, 9)
    c.drawString(22 * mm, y + 1 * mm, "DESCRIPTION")
    c.drawRightString(w - 22 * mm, y + 1 * mm, "AMOUNT")
    y -= 11 * mm
    c.setFont(regular, 11)
    c.setFillColor(INK)
    desc = inv.get("description") or "Creator services"
    if deal and deal.get("listing_title"):
        desc = f"{desc} for {deal['listing_title']}"
    c.drawString(22 * mm, y, desc[:80])
    c.drawRightString(w - 22 * mm, y, money(inv["amount"]))
    c.setStrokeColor(LINE)
    c.line(18 * mm, y - 5 * mm, w - 18 * mm, y - 5 * mm)
    y -= 13 * mm
    c.setFont(bold, 12)
    c.drawString(22 * mm, y, "Total")
    c.drawRightString(w - 22 * mm, y, money(inv["amount"]))

    y -= 20 * mm
    c.setFont(regular, 10)
    c.setFillColor(MUTED)
    status = inv.get("status", "pending")
    lines = []
    if status == "paid" and deal and deal.get("payouts"):
        p = deal["payouts"][-1]
        lines.append(f"Paid by UPI to {p['upi']} on {p['at'][:10]}. UTR {p['utr']}.")
        lines.append("Released from JodiDar escrow after the post was verified.")
    elif inv.get("off_platform"):
        lines.append(f"Due by {inv['due']}. Please pay by UPI or bank transfer.")
    else:
        lines.append(f"Held in JodiDar escrow. Released by UPI once the post is verified (by {inv['due']}).")
    lines.append("Demo invoice generated by JodiDar AI. Not a tax invoice.")
    for ln in lines:
        c.drawString(18 * mm, y, ln)
        y -= 6 * mm

    c.setFillColor(VIOLET if status == "paid" else ORANGE)
    c.roundRect(w - 52 * mm, h - 62 * mm, 34 * mm, 9 * mm, 4, stroke=0, fill=1)
    c.setFillColor(colors.white)
    c.setFont(bold, 10)
    c.drawCentredString(w - 35 * mm, h - 59 * mm, status.upper())
    c.showPage()
    c.save()
    return buf.getvalue()


def media_kit_pdf(kit: dict) -> bytes:
    regular, bold = _fonts()
    buf = io.BytesIO()
    c = Canvas(buf, pagesize=A4)
    w, h = A4
    _brand_bar(c, w, h)
    _wordmark(c, 18 * mm, h - 22 * mm)
    c.setFont(regular, 9)
    c.setFillColor(MUTED)
    c.drawRightString(w - 18 * mm, h - 22 * mm, f"Media kit · {kit['generated_on']}")

    y = h - 44 * mm
    c.setFont(bold, 24)
    c.setFillColor(INK)
    c.drawString(18 * mm, y, kit["name"])
    c.setFont(regular, 11)
    c.setFillColor(MUTED)
    c.drawString(18 * mm, y - 7 * mm, f"@{kit['handle']} · {kit['niche']} · {', '.join(kit['languages'])}{' · ' + kit['location'] if kit.get('location') else ''}")
    y -= 18 * mm
    c.setFont(bold, 13)
    c.setFillColor(INK)
    c.drawString(18 * mm, y, kit["copy"]["headline"][:90])
    y -= 7 * mm
    c.setFont(regular, 10.5)
    c.setFillColor(MUTED)
    for line in _wrap(kit["copy"]["bio"], regular, 10.5, w - 36 * mm):
        c.drawString(18 * mm, y, line)
        y -= 5.5 * mm

    if kit.get("stats"):
        y -= 6 * mm
        tiles = kit["stats"]
        tw = (w - 36 * mm - 3 * 4 * mm) / 4
        for i, t in enumerate(tiles[:4]):
            x = 18 * mm + i * (tw + 4 * mm)
            c.setFillColor(SOFT)
            c.roundRect(x, y - 18 * mm, tw, 20 * mm, 6, stroke=0, fill=1)
            c.setFillColor(MUTED)
            c.setFont(regular, 8)
            c.drawString(x + 4 * mm, y - 4 * mm, t["label"] + (" *" if t.get("simulated") else ""))
            c.setFillColor(INK)
            c.setFont(bold, 15)
            c.drawString(x + 4 * mm, y - 13 * mm, t["value"])
        y -= 28 * mm

    if kit.get("formats"):
        c.setFont(bold, 11)
        c.setFillColor(INK)
        c.drawString(18 * mm, y, "What performs best")
        y -= 6 * mm
        c.setFont(regular, 10)
        c.setFillColor(MUTED)
        for f in kit["formats"]:
            c.drawString(18 * mm, y, f"{f['topic']}: median {f['views']} views" + (" *" if f.get("simulated") else ""))
            y -= 5.5 * mm
        y -= 4 * mm

    if kit.get("rates"):
        c.setFont(bold, 11)
        c.setFillColor(INK)
        c.drawString(18 * mm, y, "Rates (priced on reach)")
        y -= 7 * mm
        for r in kit["rates"]:
            c.setFont(regular, 10.5)
            c.setFillColor(INK)
            c.drawString(18 * mm, y, r["label"])
            c.setFont(bold, 10.5)
            c.drawRightString(w - 18 * mm, y, r["value"])
            c.setStrokeColor(LINE)
            c.line(18 * mm, y - 2.5 * mm, w - 18 * mm, y - 2.5 * mm)
            y -= 8 * mm
        c.setFont(regular, 8.5)
        c.setFillColor(MUTED)
        c.drawString(18 * mm, y, "Ranges, not promises. Final price depends on deliverables, usage rights and fit with your brand.")
        y -= 8 * mm

    if kit.get("audience"):
        c.setFont(bold, 11)
        c.setFillColor(INK)
        c.drawString(18 * mm, y, "Audience" + (" *" if kit["audience"].get("simulated") else ""))
        y -= 6 * mm
        c.setFont(regular, 10)
        c.setFillColor(MUTED)
        c.drawString(18 * mm, y, kit["audience"]["line"][:110])
        y -= 10 * mm

    c.setFont(regular, 9.5)
    c.setFillColor(MUTED)
    trust = kit.get("trust")
    footer = [f"Book through {kit['link']} (escrow-protected, paid by UPI)."]
    if trust:
        footer.insert(0, f"Trust {trust['score']}/100 from insights connected via the official API.")
    if kit.get("safety_note"):
        footer.append(kit["safety_note"])
    if kit.get("reference_note"):
        footer.append(kit["reference_note"])
    if kit.get("has_simulated"):
        footer.append("* Simulated: not shared by the creator; illustrative for the demo.")
    y = max(y, 40 * mm)
    for ln in footer:
        for part in _wrap(ln, regular, 9.5, w - 36 * mm):
            c.drawString(18 * mm, y, part)
            y -= 5 * mm
    c.showPage()
    c.save()
    return buf.getvalue()


def _wrap(text: str, font: str, size: float, width: float) -> list[str]:
    words, lines, cur = text.split(), [], ""
    for wd in words:
        trial = f"{cur} {wd}".strip()
        if pdfmetrics.stringWidth(trial, font, size) <= width:
            cur = trial
        else:
            if cur:
                lines.append(cur)
            cur = wd
    if cur:
        lines.append(cur)
    return lines
